"""Build the blind retrieval fixtures from specs.json (frozen) and targets.json (added later).

Claims, queries, design elements and anchors come from a fixed template, so no query is phrased with knowledge of
the target papers. Run from this directory:  python build_fixtures.py [--freeze]
--freeze writes MANIFEST.json with the SHA-256 of specs.json and of this script, before targets exist.
"""
from __future__ import annotations

import datetime
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def fixture_from_spec(spec: dict, split: str) -> dict:
    m, b, t, d = spec["method"], spec["baseline"], spec["task"], spec["data"]
    return {
        "id": spec["id"], "split": split,
        "claim": f"A controlled comparison of {m} against {b} for {t} on {d}, testing whether the gain holds",
        "queries": [
            f"{m} {t}",
            f"{m} versus {b} {t}",
            f"{b} strong baseline {t}",
            f"{m} {t} evaluation {d}",
            f"does {m} improve over {b}",
        ],
        "anchor": t,
        "design": [f"{b} baseline", "same hyperparameter tuning budget", "multiple random seeds"],
        "seeds": spec.get("seeds") or [],
        "known_relevant": [],
        "provenance": "Blind fixture: claim and queries generated by template from specs.json before targets "
                      "were searched; targets found afterwards by web search (see targets.json).",
    }


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    specs = json.loads((HERE / "specs.json").read_text(encoding="utf-8"))
    if "--freeze" in sys.argv:
        (HERE / "MANIFEST.json").write_text(json.dumps({
            "frozen_at_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
            "specs.json": sha(HERE / "specs.json"), "build_fixtures.py": sha(HERE / "build_fixtures.py"),
            "note": "Recorded before any target search. Changing either file invalidates the blind set."},
            indent=2) + "\n", encoding="utf-8")
    targets_path = HERE / "targets.json"
    targets = json.loads(targets_path.read_text(encoding="utf-8")) if targets_path.exists() else {}
    out = []
    for spec in specs["specs"]:
        fx = fixture_from_spec(spec, "blind")
        fx["known_relevant"] = targets.get(spec["id"], [])
        if fx["known_relevant"]:
            out.append(fx)
    for spec in specs["controls"]:
        out.append(fixture_from_spec(spec, "control"))
    (HERE / "fixtures").mkdir(exist_ok=True)
    for fx in out:
        (HERE / "fixtures" / f"{fx['split']}_{fx['id']}.json").write_text(json.dumps(fx, indent=2) + "\n",
                                                                           encoding="utf-8")
    print(f"{len(out)} fixtures written ({sum(1 for f in out if f['split'] == 'blind')} blind, "
          f"{sum(1 for f in out if f['split'] == 'control')} control)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
