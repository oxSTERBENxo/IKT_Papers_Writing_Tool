"""Export research reports to an Obsidian vault as plain Markdown notes.

Layout inside the vault (folder name configurable, default "Scientific Research"):

    <vault>/<folder>/Research Dashboard.md
    <vault>/<folder>/Projects/<report title>.md   one note per report
    <vault>/<folder>/Papers/<paper title>.md       one note per verified reference

Safety rules:
- Only the region between ``%% sra:begin %%`` and ``%% sra:end %%`` (Obsidian comments, invisible in reading view)
  and a fixed set of frontmatter keys are written by the exporter. Everything else in a note belongs to the user and
  is kept. Frontmatter keys the user adds are kept; user tags are merged with the exporter's tags.
- Notes are found again by their ``sra_id`` frontmatter key, so a re-export updates the same note even after the user
  renamed or moved it inside the research folder. Nothing is ever deleted.
- The hash of the managed region is stored (``sra_hash``). If the user edited inside the managed region, or removed its
  markers, the note is skipped with a warning unless ``overwrite_managed=True``.
- Source reports are only read, never written.

Paper notes are generated only for references whose verification status is "verified" (from ``verify-refs``). Their
content is copied from the report fields (title, authors, year, venue, identifiers, findings, limitations, read level),
attributed to the report it came from; missing fields are written as "not reported". Nothing is generated.
"""
from __future__ import annotations

import datetime
import hashlib
import json
import os
import re
import unicodedata
from pathlib import Path

from . import report as rpt
from .models import normalize_arxiv_id, normalize_doi

DEFAULT_FOLDER = "Scientific Research"
PROJECTS_DIR, PAPERS_DIR = "Projects", "Papers"
DASHBOARD = "Research Dashboard"
BEGIN, END = "%% sra:begin %%", "%% sra:end %%"
NOTICE = ("%% This section is generated by scientific-research-assistant and is replaced on re-export. "
          "Write your own notes above or below it. %%")
MANAGED_KEYS = ("title", "research_type", "created", "updated", "tags", "research_status", "source_report",
                "sra_id", "sra_kind", "sra_hash")
TYPE_LABELS = {"opportunity_report": "Research opportunities", "literature_review": "Literature reviews",
               "reproducibility_report": "Reproducibility reports", "research_proposal": "Research proposals",
               "paper": "Papers"}
WINDOWS_RESERVED = {"con", "prn", "aux", "nul", *(f"com{i}" for i in range(1, 10)), *(f"lpt{i}" for i in range(1, 10))}
MAX_STEM = 120


class ExportError(Exception):
    """The export cannot proceed (bad vault path, bad folder name, unreadable report)."""


# -- configuration -----------------------------------------------------------
def known_vaults() -> list[str]:
    """Vault folders listed in Obsidian's own settings file (read-only), to help with a wrong path."""
    base = os.environ.get("APPDATA") or str(Path.home() / ".config")
    try:
        data = json.loads((Path(base) / "obsidian" / "obsidian.json").read_text(encoding="utf-8"))
        return [v.get("path") for v in (data.get("vaults") or {}).values() if v.get("path")]
    except (OSError, ValueError):
        return []


def resolve_vault(path: str | None, allow_plain_folder: bool = False) -> Path:
    raw = path or os.environ.get("SRA_OBSIDIAN_VAULT")
    if not raw:
        raise ExportError("no vault given: pass --vault PATH or set SRA_OBSIDIAN_VAULT")
    vault = Path(os.path.expandvars(os.path.expanduser(raw.strip().strip('"'))))
    hint = ""
    vaults = known_vaults()
    if vaults:
        hint = " Vaults Obsidian knows about: " + "; ".join(vaults)
    if not vault.exists():
        raise ExportError(f"vault path does not exist: {vault}.{hint}")
    if not vault.is_dir():
        raise ExportError(f"vault path is a file, not a folder: {vault} (the vault is the folder that holds your "
                          f"notes, not Obsidian.exe).{hint}")
    if not (vault / ".obsidian").is_dir() and not allow_plain_folder:
        raise ExportError(f"{vault} has no .obsidian folder, so it does not look like an Obsidian vault. Open it in "
                          f"Obsidian once, or pass --allow-plain-folder.{hint}")
    return vault.resolve()


def research_root(vault: Path, folder: str | None) -> Path:
    raw = (folder if folder is not None else os.environ.get("SRA_OBSIDIAN_FOLDER") or DEFAULT_FOLDER).strip()
    if raw.startswith(("/", "\\")):
        raise ExportError(f"research folder must be a relative path inside the vault: {raw!r}")
    name = raw.strip("/\\")
    if not name:
        raise ExportError("the research folder name is empty")
    parts = re.split(r"[\\/]+", name)
    if any(p in ("", ".", "..") for p in parts) or Path(name).is_absolute() or ":" in name:
        raise ExportError(f"research folder must be a relative path inside the vault: {name!r}")
    root = (vault / Path(*[safe_stem(p) for p in parts])).resolve()
    if vault not in root.parents:
        raise ExportError(f"research folder escapes the vault: {root}")
    return root


# -- text helpers ------------------------------------------------------------
def safe_stem(name: str, limit: int = MAX_STEM) -> str:
    """A file name stem that Windows, macOS, Linux and Obsidian links accept. Unicode is kept (NFC)."""
    s = unicodedata.normalize("NFC", str(name or ""))
    s = re.sub(r'[\\/:*?"<>|#^\[\]\x00-\x1f]', " ", s)
    s = re.sub(r"\s+", " ", s).strip(" .")
    if len(s) > limit:
        s = s[:limit].rsplit(" ", 1)[0].rstrip(" .") or s[:limit]
    if not s:
        s = "Untitled"
    if s.split(".")[0].lower() in WINDOWS_RESERVED:
        s = f"_{s}"
    return s


def md_escape(text) -> str:
    """Escape characters that would turn plain metadata (titles, authors) into Markdown or links."""
    s = re.sub(r"\s+", " ", str(text or "")).strip()
    return re.sub(r"([\\`*_\[\]<>|#])", r"\\\1", s)


def wikilink(target: str, alias: str | None = None, in_table: bool = False) -> str:
    alias = re.sub(r"[\[\]|\n]", " ", alias).strip() if alias else None
    sep = "\\|" if in_table else "|"
    return f"[[{target}{sep}{alias}]]" if alias and alias != target else f"[[{target}]]"


def yaml_value(value) -> str:
    """JSON scalars and flow lists are valid YAML; JSON escaping handles quotes, colons and Unicode."""
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(json.dumps(str(v), ensure_ascii=False) for v in value) + "]"
    if isinstance(value, bool) or value is None:
        return json.dumps(value)
    return json.dumps(str(value), ensure_ascii=False)


def digest(text: str) -> str:
    return hashlib.sha256(text.replace("\r\n", "\n").strip().encode("utf-8")).hexdigest()[:16]


# -- note parsing ------------------------------------------------------------
FM_RE = re.compile(r"\A---\r?\n(.*?)\r?\n---\r?\n?", re.S)


def split_frontmatter(text: str) -> tuple[list[tuple[str | None, str]], str]:
    """Return ([(key, raw block)], body). A block is a top-level key line plus its indented or list lines."""
    m = FM_RE.match(text)
    if not m:
        return [], text
    blocks: list[tuple[str | None, str]] = []
    for line in m.group(1).split("\n"):
        line = line.rstrip("\r")
        key = re.match(r"^([A-Za-z0-9_][A-Za-z0-9_\- ]*):", line)
        if key:
            blocks.append((key.group(1).strip(), line))
        elif blocks:
            k, raw = blocks[-1]
            blocks[-1] = (k, raw + "\n" + line)
        else:
            blocks.append((None, line))
    return blocks, text[m.end():]


def fm_scalar(blocks, key: str) -> str | None:
    for k, raw in blocks:
        if k == key:
            value = raw.split(":", 1)[1].strip()
            try:
                parsed = json.loads(value)
                return parsed if isinstance(parsed, str) else str(parsed)
            except ValueError:
                return value.strip("'\"") or None
    return None


def fm_list(blocks, key: str) -> list[str]:
    for k, raw in blocks:
        if k != key:
            continue
        first, *rest = raw.split("\n")
        inline = first.split(":", 1)[1].strip()
        items = []
        if inline.startswith("["):
            items = [x.strip().strip("'\"") for x in inline.strip("[]").split(",")]
        elif inline:
            items = [x.strip().strip("'\"") for x in re.split(r"[,\s]+", inline)]
        items += [ln.strip()[1:].strip().strip("'\"") for ln in rest if ln.strip().startswith("-")]
        return [i for i in items if i]
    return []


def managed_region(body: str) -> tuple[int, int] | None:
    """Character span of the managed content (between the markers), or None when the markers are missing."""
    b = body.find(BEGIN)
    if b < 0:
        return None
    e = body.find(END, b + len(BEGIN))
    return (b + len(BEGIN), e) if e >= 0 else None


def build_note(old_text: str | None, managed_fm: dict, managed_body: str) -> str:
    """Merge exporter-owned frontmatter and body region into an existing note (or create one)."""
    region = "\n" + NOTICE + "\n\n" + managed_body.strip() + "\n\n"
    fm = dict(managed_fm)
    fm["sra_hash"] = digest(managed_body)
    if old_text is None:
        lines = [f"{k}: {yaml_value(v)}" for k, v in fm.items()]
        return "---\n" + "\n".join(lines) + "\n---\n\n" + BEGIN + region + END + "\n"
    blocks, body = split_frontmatter(old_text)
    user_tags = fm_list(blocks, "tags")
    fm["tags"] = list(dict.fromkeys([*fm.get("tags", []), *user_tags]))
    created = fm_scalar(blocks, "created")
    if created:
        fm["created"] = created
    out, seen = [], set()
    for k, raw in blocks:
        if k in fm:
            out.append(f"{k}: {yaml_value(fm[k])}")
            seen.add(k)
        else:
            out.append(raw)
    out += [f"{k}: {yaml_value(v)}" for k, v in fm.items() if k not in seen]
    span = managed_region(body)
    if span:
        body = body[:span[0] - len(BEGIN)] + BEGIN + region + body[span[1]:]
    else:
        body = body.rstrip() + "\n\n" + BEGIN + region + END + "\n"
    return "---\n" + "\n".join(out) + "\n---\n" + (body if body.startswith("\n") else "\n" + body)


# -- vault index -------------------------------------------------------------
class Vault:
    def __init__(self, root: Path):
        self.root = root
        self.by_id: dict[str, Path] = {}
        self.meta: dict[str, dict] = {}
        if root.exists():
            for path in sorted(root.rglob("*.md")):
                try:
                    blocks, _ = split_frontmatter(path.read_text(encoding="utf-8"))
                except (OSError, UnicodeDecodeError):
                    continue
                sid = fm_scalar(blocks, "sra_id")
                if sid and sid not in self.by_id:
                    self.by_id[sid] = path
                    self.meta[sid] = {k: fm_scalar(blocks, k) for k in MANAGED_KEYS if k != "tags"}
        self.reserved: dict[Path, str] = {}

    def path_for(self, sid: str, folder: str, stem: str) -> Path:
        """Existing note for this id, else a new unique path (" (2)", " (3)" on collisions)."""
        if sid in self.by_id:
            return self.by_id[sid]
        base = self.root / folder
        candidate, n = base / f"{stem}.md", 2
        while (candidate.exists() or candidate in self.reserved) and self.reserved.get(candidate) != sid:
            candidate, n = base / f"{stem} ({n}).md", n + 1
        self.reserved[candidate] = sid
        return candidate


# -- identities ----------------------------------------------------------------
def report_id(source: Path) -> str:
    return "report:" + hashlib.sha1(str(source.resolve()).lower().encode("utf-8")).hexdigest()[:12]


def paper_id(p: dict) -> str | None:
    doi = normalize_doi(p.get("doi"))
    if doi and not doi.lower().startswith("10.48550/arxiv."):
        return f"paper:doi:{doi.lower()}"
    arx = normalize_arxiv_id(p.get("arxiv_id")) or (normalize_arxiv_id(doi.split("arxiv.", 1)[1]) if doi and
                                                    "arxiv." in doi.lower() else None)
    if arx:
        return f"paper:arxiv:{arx}"
    if p.get("pmid"):
        return f"paper:pmid:{p['pmid']}"
    if p.get("url"):
        return "paper:url:" + hashlib.sha1(p["url"].encode("utf-8")).hexdigest()[:12]
    return None


def is_verified(p: dict) -> bool:
    return (p.get("verification") or {}).get("status") == "verified"


def research_status(report: dict) -> str:
    t = report.get("type")
    if t == "opportunity_report":
        verdicts = [((o.get("decision") or {}).get("verdict")) for o in report.get("opportunities") or []]
        for v in ("go", "conditional_go"):
            if v in verdicts:
                return v.replace("_", "-")
        return "no-go" if verdicts and all(v == "no_go" for v in verdicts) else "exploring"
    if t == "reproducibility_report":
        statuses = [c.get("result_status") for c in report.get("reproduction_candidates") or []]
        for s in ("reproduced", "partially_reproduced", "failed_to_reproduce"):
            if s in statuses:
                return s.replace("_", "-")
        return "assessed" if statuses else "exploring"
    if t == "research_proposal":
        return "proposal"
    return "review" if t == "literature_review" else "exploring"


# -- rendering -----------------------------------------------------------------
class ObsidianRenderer(rpt.Renderer):
    """The normal report renderer, with citations as wikilinks to paper notes."""

    def __init__(self, report: dict, paper_links: dict[str, str]):
        super().__init__(report)
        self.paper_links = paper_links  # citation key -> note stem

    def cite(self, keys) -> str:
        keys = [k for k in (keys if isinstance(keys, list) else [keys]) if k]
        if not keys:
            return ""
        parts = []
        for k in keys:
            p = self.papers.get(k)
            if p and k in self.paper_links:
                parts.append(wikilink(self.paper_links[k], rpt.cite_label(p)))
            elif p:
                url = rpt.paper_url(p)
                parts.append(f"[{rpt.cite_label(p)}]({url})" if url else rpt.cite_label(p))
            else:
                parts.append(f"(unknown reference {k})")
        return "(" + "; ".join(parts) + ")"

    @staticmethod
    def cell(value) -> str:
        if value is None or value == "" or value == []:
            return "not reported"
        if isinstance(value, list):
            value = "; ".join(str(v) for v in value)
        text = re.sub(r"\s+", " ", str(value))
        out, last = [], 0
        for m in re.finditer(r"\[\[[^\]]*\]\]", text):
            out.append(text[last:m.start()].replace("|", "/"))
            out.append(m.group(0).replace("\\|", "|").replace("|", "\\|"))
            last = m.end()
        out.append(text[last:].replace("|", "/"))
        return "".join(out)

    def references(self) -> str:
        papers = self.report.get("papers") or []
        if not papers:
            return rpt.MISSING
        lines = []
        for i, p in enumerate(sorted(papers, key=lambda p: rpt.cite_label(p).lower()), 1):
            authors = p.get("authors") or []
            who = ", ".join(authors[:6]) + (" et al." if len(authors) > 6 else "") or "Unknown authors"
            status = (p.get("verification") or {}).get("status")
            mark = "" if status == "verified" else f" **[reference {status or 'not verified'}]**"
            note = f" {wikilink(self.paper_links[p['key']], 'note')}" if p.get("key") in self.paper_links else ""
            lines.append(f"{i}. {md_escape(who)} ({p.get('year') or 'n.d.'}). *{md_escape(p.get('title'))}*. "
                         f"{md_escape(p.get('venue')) + '. ' if p.get('venue') else ''}{rpt.paper_url(p) or ''}"
                         f"{note}{mark}")
        return "\n".join(lines)


GLANCE_TYPES = {"opportunity_report": "Research opportunity report", "literature_review": "Literature review",
                "reproducibility_report": "Reproducibility report", "research_proposal": "Research proposal"}
RESULT_LABELS = {"not_assessed": "not assessed", "assessed_only": "assessed, not run",
                 "reproduced": "reproduced", "partially_reproduced": "partly reproduced",
                 "failed_to_reproduce": "failed to reproduce"}


def at_a_glance(data: dict, r: ObsidianRenderer) -> str:
    """A short callout at the top of a project note: question, type, data, questions/hypotheses, conclusion.

    Built only from fields already in the report; anything missing is left out rather than invented.
    """
    def plain(item) -> str:
        if isinstance(item, dict):
            item = item.get("text")
        return re.sub(r"\s+", " ", r.text(item)).strip() if item else ""

    def points(value, limit=None) -> list[str]:
        items = value if isinstance(value, list) else ([value] if value else [])
        out = [p for p in (plain(v) for v in items) if p]
        return out[:limit] if limit else out

    rtype = data.get("type")
    prop = data.get("proposal") or {}
    sections = data.get("sections") or {}
    cons = data.get("constraints") or {}
    L = ["> [!abstract] At a glance"]
    rq = points(prop.get("research_question"))
    main = rq[0] if len(rq) == 1 else md_escape(data.get("title") or "")
    L.append(f"> **{'Main question' if main.rstrip().endswith('?') else 'Topic'}:** {main}")
    L.append(">")
    L.append(f"> **Type:** {GLANCE_TYPES.get(rtype, rtype or 'report')}"
             + (f" · **Field:** {md_escape(cons['field'])}" if cons.get("field") else "")
             + (f" · **Status:** {research_status(data)}"))
    sets = data.get("datasets") or []
    if sets:
        names = [f"[{md_escape(d.get('name'))}]({d['url']})" if d.get("url") else md_escape(d.get("name"))
                 for d in sets[:5] if d.get("name")]
        more = f" (+{len(sets) - 5} more)" if len(sets) > 5 else ""
        L += [">", f"> **Data:** {'; '.join(names)}{more}"]
    if len(rq) > 1:
        L += [">", "> **Research questions:**"] + [f"> - {q}" for q in rq]
    hyp = points(prop.get("hypothesis"))
    if hyp:
        L += [">", "> **Hypotheses:**"] + [f"> - {h}" for h in hyp]
    opps = data.get("opportunities") or []
    if opps:
        L += [">", "> **Questions considered and decisions:**", ">",
              "> | Question | Type | Decision |", "> | --- | --- | --- |"]
        for o in opps:
            qtype = rpt.QUESTION_TYPES.get(o.get("question_type")) or (o.get("mode") or "not classified")
            verdict = rpt.VERDICTS.get((o.get("decision") or {}).get("verdict"), "not decided")
            L.append(f"> | {r.cell(r.text(o.get('title')))} | {r.cell(qtype)} | **{verdict}** |")
    cands = data.get("reproduction_candidates") or []
    if cands:
        L += [">", "> **Papers assessed:**", ">", "> | Paper | Result |", "> | --- | --- |"]
        for c in cands:
            L.append(f"> | {r.cell(r.text(c.get('title') or c.get('paper')))} | "
                     f"{RESULT_LABELS.get(c.get('result_status', 'assessed_only'), c.get('result_status'))} |")
    concl = points(sections.get("recommendation") or prop.get("contribution") or sections.get("summary"), 4)
    if concl:
        label = "Expected contribution" if rtype == "research_proposal" and not sections.get("recommendation") \
            else "Conclusion"
        L += [">", f"> **{label}:**"] + ([f"> {concl[0]}"] if len(concl) == 1 else [f"> - {c}" for c in concl])
    return "\n".join(L) + "\n"


def _strip_title(md: str) -> str:
    """The note title is shown by Obsidian; drop the report's own H1 so it is not duplicated."""
    return re.sub(r"\A# [^\n]*\n+", "", md)


# -- export ----------------------------------------------------------------------
def load_report(path: str | Path) -> tuple[dict, Path]:
    src = Path(path)
    try:
        data = json.loads(src.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ExportError(f"cannot read report {src}: {exc}") from exc
    if data.get("type") not in rpt.REPORT_TYPES:
        raise ExportError(f"{src}: not a report JSON (type {data.get('type')!r})")
    return data, src.resolve()


def export(reports: list[tuple[dict, Path]], vault: Path, folder: str | None = None, papers: bool = True,
           status_override: str | None = None, overwrite_managed: bool = False, dry_run: bool = False,
           today: str | None = None) -> dict:
    """Export reports (already loaded) into the vault. Returns a summary of actions and warnings."""
    root = research_root(vault, folder)
    today = today or datetime.date.today().isoformat()
    index = Vault(root)
    actions: list[dict] = []
    warnings: list[str] = []

    # Every report already exported to this vault takes part in cross-links and paper notes, so a paper cited by
    # two reports exported on different days still links to both. Their sources are read again, never written.
    all_reports: dict[str, tuple[dict, Path]] = {}
    missing: dict[str, dict] = {}  # exported earlier, source report no longer found: listed, not rebuilt
    for sid, meta in index.meta.items():
        if meta.get("sra_kind") == "project" and meta.get("source_report"):
            src = Path(meta["source_report"])
            if src.exists():
                try:
                    all_reports[sid] = load_report(src)
                except ExportError as exc:
                    warnings.append(f"previously exported report not re-read: {exc}")
            else:
                missing[sid] = {**meta, "stem": index.by_id[sid].stem}
                warnings.append(f"previously exported report no longer at {src}; its note is kept as it is")
    for data, src in reports:
        all_reports[report_id(src)] = (data, src)
        missing.pop(report_id(src), None)

    # Note paths for projects and papers, decided before writing so every link points at a real note.
    project_stem: dict[str, str] = {}
    for rid, (data, src) in all_reports.items():
        path = index.path_for(rid, PROJECTS_DIR, safe_stem(data.get("title") or src.stem))
        project_stem[rid] = path.stem
    paper_records: dict[str, list[tuple[str, dict]]] = {}
    key_to_pid: dict[str, dict[str, str]] = {}
    for rid, (data, _src) in all_reports.items():
        key_to_pid[rid] = {}
        for p in data.get("papers") or []:
            pid = paper_id(p)
            if pid and is_verified(p):
                paper_records.setdefault(pid, []).append((rid, p))
                key_to_pid[rid][p.get("key")] = pid
    # Deterministic order (by source path), so re-exports produce identical notes whatever order reports load in.
    for recs in paper_records.values():
        recs.sort(key=lambda rec: str(all_reports[rec[0]][1]).lower())
    paper_stem: dict[str, str] = {}
    if papers:
        for pid, recs in paper_records.items():
            path = index.path_for(pid, PAPERS_DIR, safe_stem(recs[0][1].get("title") or pid))
            paper_stem[pid] = path.stem

    def write(sid: str, folder_name: str, stem: str, fm: dict, body: str, kind: str):
        path = index.path_for(sid, folder_name, stem)
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old is not None:
            blocks, old_body = split_frontmatter(old)
            span = managed_region(old_body)
            stored = fm_scalar(blocks, "sra_hash")
            if span is None and not overwrite_managed:
                warnings.append(f"skipped {path.name}: its managed markers were removed; restore them or use "
                                "--overwrite-managed")
                actions.append({"action": "skipped", "kind": kind, "path": str(path)})
                return
            if span and stored and digest(old_body[span[0]:span[1]].replace(NOTICE, "")) != stored \
                    and not overwrite_managed:
                warnings.append(f"skipped {path.name}: the generated section was edited by hand; move your edits "
                                "outside the markers, or use --overwrite-managed")
                actions.append({"action": "skipped", "kind": kind, "path": str(path)})
                return
        new = build_note(old, fm, body)
        if old is not None and new == old:
            actions.append({"action": "unchanged", "kind": kind, "path": str(path)})
            return
        if old is not None and _same_except_updated(old, new):
            actions.append({"action": "unchanged", "kind": kind, "path": str(path)})
            return
        actions.append({"action": "updated" if old is not None else "created", "kind": kind, "path": str(path)})
        if not dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            tmp = path.with_name(path.name + ".sra-tmp")
            tmp.write_text(new, encoding="utf-8", newline="\n")
            os.replace(tmp, path)
            index.by_id[sid] = path

    # Projects that share verified papers link to each other.
    shared: dict[str, set[str]] = {rid: set() for rid in all_reports}
    for pid, recs in paper_records.items():
        rids = {r for r, _ in recs}
        for r in rids:
            shared[r] |= rids - {r}

    # Every known project is re-rendered (its generated section only), so links added by a new report also appear
    # in the notes of reports exported earlier. Their source files are read, never written.
    exported_ids = set(all_reports)
    for rid in sorted(exported_ids, key=lambda r: project_stem[r].lower()):
        data, src = all_reports[rid]
        links = {k: paper_stem[pid] for k, pid in key_to_pid[rid].items() if pid in paper_stem}
        renderer = ObsidianRenderer(data, links)
        body = _strip_title(renderer.render(
            (rpt.TEMPLATE_DIR / f"{data['type']}.md").read_text(encoding="utf-8")))
        related = sorted(shared[rid], key=lambda r: project_stem[r].lower())
        extra = [at_a_glance(data, renderer),
                 f"> Exported from `{src}` on {today}. The research report itself is unchanged.", ""]
        if related:
            extra += ["## Related research", ""]
            for r in related:
                n = len({pid for pid in key_to_pid[rid].values()} & {pid for pid in key_to_pid[r].values()})
                extra.append(f"- {wikilink(project_stem[r])} ({TYPE_LABELS.get(all_reports[r][0].get('type'), '')}; "
                             f"{n} shared paper{'s' if n != 1 else ''})")
            extra.append("")
        extra += [f"Back to {wikilink(DASHBOARD)}", ""]
        rtype = data.get("type")
        fm = {"title": data.get("title") or src.stem, "research_type": rtype,
              "created": data.get("date") or today, "updated": today,
              "tags": ["research", f"research/{rtype.replace('_', '-')}", "sra"],
              "research_status": status_override or research_status(data), "source_report": str(src),
              "sra_id": rid, "sra_kind": "project"}
        write(rid, PROJECTS_DIR, safe_stem(data.get("title") or src.stem), fm,
              "\n".join(extra) + "\n" + body, "project")

    if papers:
        for pid in sorted(paper_records):
            recs = paper_records[pid]
            write(pid, PAPERS_DIR, safe_stem(recs[0][1].get("title") or pid),
                  _paper_fm(recs, today), _paper_body(recs, all_reports, project_stem), "paper")
    unverified = sum(1 for data, _ in reports for p in data.get("papers") or [] if not is_verified(p))
    if papers and unverified:
        warnings.append(f"{unverified} reference(s) without a 'verified' check got no paper note; run verify-refs on "
                        "the report to include them")

    write("dashboard", "", DASHBOARD, {"title": DASHBOARD, "research_type": "dashboard", "created": today,
                                     "updated": today, "tags": ["research", "sra"], "sra_id": "dashboard",
                                     "sra_kind": "dashboard"},
          _dashboard(all_reports, project_stem, paper_records, missing), "dashboard")
    return {"vault": str(vault), "folder": str(root), "dry_run": dry_run, "actions": actions, "warnings": warnings}


def _same_except_updated(old: str, new: str) -> bool:
    pat = re.compile(r"^updated: .*$", re.M)
    return pat.sub("", old) == pat.sub("", new)


def _paper_fm(recs, today: str) -> dict:
    p = recs[0][1]
    return {"title": p.get("title"), "research_type": "paper", "created": today, "updated": today,
            "tags": ["paper", "sra"], "authors": p.get("authors") or [], "year": str(p.get("year") or ""),
            "doi": p.get("doi") or "", "arxiv": p.get("arxiv_id") or "", "sra_id": paper_id(p), "sra_kind": "paper"}


def _paper_body(recs, all_reports, project_stem) -> str:
    p = recs[0][1]
    authors = p.get("authors") or []
    links = []
    doi = p.get("doi")
    if doi and not str(doi).lower().startswith("10.48550/arxiv."):
        links.append(f"[DOI {md_escape(doi)}](https://doi.org/{doi})")
    if p.get("arxiv_id"):
        links.append(f"[arXiv {md_escape(p['arxiv_id'])}](https://arxiv.org/abs/{p['arxiv_id']})")
    if not links and rpt.paper_url(p):
        links.append(rpt.paper_url(p))
    lines = [f"**Authors:** {md_escape(', '.join(authors)) if authors else 'not reported'}  ",
             f"**Year:** {p.get('year') or 'not reported'}  ",
             f"**Venue:** {md_escape(p.get('venue')) if p.get('venue') else 'not reported'}  ",
             f"**Links:** {' · '.join(links) if links else 'not reported'}  ",
             f"**Reference check:** verified ({(p.get('verification') or {}).get('via') or 'source not recorded'})",
             "", "> Summaries below are copied from the research reports that cite this paper, with how deeply the "
             "paper was read there. They are not generated.", ""]
    for field, heading in (("findings", "Summary"), ("limitations", "Limitations"), ("method", "Method"),
                           ("datasets", "Data")):
        entries = [(rid, rec) for rid, rec in recs if rec.get(field)]
        if field in ("method", "datasets") and not entries:
            continue
        lines += [f"## {heading}", ""]
        if not entries:
            lines.append("not reported")
        for rid, rec in entries:
            lines.append(f"- From {wikilink(project_stem[rid])} (read level: {rec.get('read_level') or 'not recorded'}): "
                         f"{re.sub(chr(10) + '+', ' ', str(rec[field]))}")
        lines.append("")
    lines += ["## Related research", ""]
    for rid, rec in recs:
        rtype = all_reports[rid][0].get("type")
        lines.append(f"- {wikilink(project_stem[rid])} ({TYPE_LABELS.get(rtype, rtype)}; role: "
                     f"{rec.get('role') or 'not recorded'})")
    lines += ["", f"Back to {wikilink(DASHBOARD)}"]
    return "\n".join(lines)


def _dashboard(all_reports, project_stem, paper_records, missing) -> str:
    lines = ["Research projects exported by scientific-research-assistant. Status comes from each report's "
             "decisions or results.", ""]
    by_type: dict[str, list[str]] = {}
    for rid, (data, _src) in all_reports.items():
        n_papers = sum(1 for recs in paper_records.values() if any(r == rid for r, _ in recs))
        row = (f"| {wikilink(project_stem[rid], in_table=True)} | {research_status(data)} | {data.get('date') or ''} "
               f"| {n_papers} |")
        by_type.setdefault(data.get("type"), []).append(row)
    for meta in missing.values():
        by_type.setdefault(meta.get("research_type"), []).append(
            f"| {wikilink(meta['stem'], in_table=True)} | {meta.get('research_status') or ''} (source report missing) "
            f"| {meta.get('created') or ''} | ? |")
    for rtype in ("opportunity_report", "literature_review", "reproducibility_report", "research_proposal"):
        rows = sorted(by_type.get(rtype, []), key=str.lower)
        if not rows:
            continue
        lines += [f"## {TYPE_LABELS[rtype]}", "", "| Project | Status | Report date | Verified papers |",
                  "| --- | --- | --- | --- |", *rows, ""]
    lines.append(f"{len(paper_records)} verified paper(s) across {len(all_reports)} project(s).")
    return "\n".join(lines)
